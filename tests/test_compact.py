"""Tests for the model-facing projections in `spice_mcp_app.compact`.

The projections exist to cut input tokens, so the danger they carry is obvious: a
projection that drops something the model needed buys a smaller number and a worse answer.
These tests are therefore written from that direction - they assert what **survives**, ref
by ref and node by node, and only then that the noise is gone.

`RCLP_NETLIST` and `SOURCE_CONFLICT_SIM` are **real captured output**, lifted from
`bench/baseline-session-32589a49.json` and from a `run_simulation` on
`fixtures/source_conflict.asc`. Invented samples would be the wrong thing to test against:
these payloads are the reason the projection is worth doing, and LTspice's log messages in
particular are inconsistent enough that a plausible-looking fake would test a shape the
tool never emits.
"""

